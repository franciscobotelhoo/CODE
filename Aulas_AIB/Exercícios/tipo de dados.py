#verificação dos tipos de dados
 
#isnumeric
n1 = input('Introduza algo: ')
print(n1.isnumeric())

#isalpha
a1 = input('Introduza algo: ')
print(a1.isalpha())

#isalnum
an1 = input('Introduza algo: ')
print(an1.isalnum())

#isupper
u1 = input('Introduza algo: ')
print (u1.isupper())

#islover
l1 = input('Introduza algo: ')
print(l1.islower())

#isprintable
d1 = input('Introduza algo: ')
print(d1.isprintable())