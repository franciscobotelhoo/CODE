#Crie um programa que leia dois valores numéricos inteiros, cria uma variável para guardar a soma desses valores numéricos. Apresente uma mensagem com o valor da soma.

n1 = int(input('Digite um valor inteiro: '))
n2 = int(input('Digite outro valor inteiro: '))

s = n1 + n2

print(f'A soma de {n1} com {n2} é {s}.')

print(f'{n1}+{n2}={s}')